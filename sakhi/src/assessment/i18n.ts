export const A_DICTS: Record<Lang, ADict> = { en, hi, te }

export function at(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const d = A_DICTS[lang] as Record<string, string>
  let s = override('assessment', lang, key) ?? d[key]
  if (s === undefined) throw new Error(`Missing assessment string "${key}" for ${lang}`)
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}
