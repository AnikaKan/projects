const { chromium } = require('playwright')
const SP = '' + (process.env.SHOTS_DIR || require('os').tmpdir()) + ''
const BASE = 'http://localhost:4176/'
const problems = []
const note = (m) => console.log(m)
const ok = (cond, msg) => { if (!cond) problems.push(msg) }
;(async () => {
  const b = await chromium.launch()
  // ── Desktop coach + mobile learner, same browser profile (same localStorage)
  const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } })
  const p = await ctx.newPage()
  p.on('pageerror', (e) => problems.push('pageerror ' + e.message))
  p.on('console', (m) => m.type() === 'error' && !/Failed to load resource/.test(m.text()) && problems.push('console ' + m.text()))
  const tid = (t) => p.getByTestId(t)
  const shot = (n) => p.screenshot({ path: `${SP}/shots/P-${n}.png`, fullPage: true })
  const overflow = async (label) => { if (await p.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) problems.push(label + ': horizontal overflow') }

  await p.goto(BASE + '#/coach')
  await p.waitForSelector('[data-testid=prototype-banner]')
  ok((await p.getByTestId(/^roster-DL-\d+$/).count()) === 6, 'roster count')
  await shot('1-roster-en')
  await tid('roster-DL-04').click()
  await shot('2-DL04-en')
  ok((await tid('coach-recommended').getAttribute('data-source')) === 'coach', 'DL-04 override shown')
  await tid('coach-lang-te').click()
  await shot('3-DL04-te')
  ok((await tid('prototype-banner').innerText()).includes('ప్రోటోటైప్'), 'te banner')
  await tid('coach-lang-en').click()

  // Review + replay lesson for DL-02 (learner language Telugu)
  await p.goto(BASE + '#/coach/learner/DL-02/session')
  await tid('session-go-teach').click()
  ok((await tid('lesson-review').getAttribute('data-play-lang')) === 'te', 'session teach: lesson replay defaults to her language (te)')
  await shot('4-DL02-session-teach')
  await tid('session-pause').click()
  await p.waitForSelector('[data-testid=learner-detail]')
  // Adjust DL-03 next lesson with reason
  await tid('roster-DL-03').click()
  await tid('coach-adjust').click()
  await tid('adjust-to-business_expenses').check()
  ok(await tid('adjust-save').isDisabled(), 'reason required')
  await tid('adjust-reason-learnerRequest').check()
  await tid('adjust-note').fill('Asked about daily costs')
  await shot('5-DL03-adjust')
  await tid('adjust-save').click()
  ok((await tid('coach-recommended').getAttribute('data-lesson')) === 'business_expenses', 'override saved')
  await p.reload()
  await p.waitForSelector('[data-testid=coach-recommended]')
  ok((await tid('coach-recommended').getAttribute('data-lesson')) === 'business_expenses', 'override persisted after reload')
  ok((await tid('coach-log').innerText()).includes('Learner asked for this topic'), 'log entry')
  await shot('6-DL03-after-adjust')

  // Hand the phone to Sunita (DL-03) → her Home on a phone-sized viewport
  await tid('open-learner-app').click()
  await p.setViewportSize({ width: 375, height: 812 })
  await p.waitForSelector('[data-testid=home-checkin]')
  await overflow('home')
  await shot('7-DL03-home-checkin-hi')
  await tid('home-checkin-cta').click()
  await tid('ci-notYet').click()
  await tid('diff-hardToCount').click()
  await tid('ci-note').fill('mera number 98765 43210')
  await tid('ci-send').click()
  ok(await tid('ci-note-error').isVisible(), 'phone number refused')
  await shot('8-checkin-refused')
  await tid('ci-note').fill('')
  await tid('ci-send').click()
  ok((await tid('ci-followup').getAttribute('data-challenge')) === 'rvp.explain', 'easier follow-up')
  await shot('9-checkin-followup-hi')
  await tid('ci-accept').click()
  await p.getByTestId('primary').first().click() // Go to Home
  await p.waitForSelector('[data-testid=home-challenge]')
  // Language switch keeps progress
  await p.goto(BASE + '#/progress')
  const levels = async () => p.evaluate(() => ['m1', 'm2', 'm3', 'm4', 'm5'].map((m) => document.querySelector(`[data-testid=prog-${m}]`).dataset.level + '/' + document.querySelector(`[data-testid=prog-${m}]`).dataset.needsPractice))
  const before = await levels()
  await p.getByRole('button', { name: /Language|भाषा|భాష/ }).click()
  await p.getByRole('dialog').getByText('తెలుగు').click()
  await p.waitForTimeout(200)
  const after = await levels()
  ok(JSON.stringify(before) === JSON.stringify(after), `levels changed on language switch ${before} → ${after}`)
  await overflow('progress')
  await shot('10-DL03-progress-te')
  note(`DL-03 levels (hi→te unchanged): ${after.join(', ')}`)

  // Coach sees the check-in and language change
  await p.setViewportSize({ width: 1280, height: 900 })
  await p.goto(BASE + '#/coach/learner/DL-03')
  await p.waitForSelector('[data-testid=coach-challenges]')
  ok((await tid('challenge-DL-03-ch1').getAttribute('data-status')) === 'notYet', 'coach sees notYet')
  ok((await tid('coach-challenges').innerText()).includes('Hard to count the money'), 'coach sees difficulty')
  ok((await tid('coach-learner-lang').innerText()).includes('తెలుగు'), 'coach sees new learner language')
  await shot('11-DL03-coach-updated')

  // Fresh learner DL-01: full flow → coach update
  await tid('coach-reset').click()
  await tid('coach-reset-yes').click()
  ok((await p.getByTestId(/^roster-DL-\d+$/).count()) === 6, 'roster after reset')
  await tid('roster-DL-03').click()
  ok((await tid('coach-recommended').getAttribute('data-source')) === 'rules', 'override cleared by reset')
  await p.setViewportSize({ width: 375, height: 812 })
  await p.goto(BASE + '#/onboarding/language')
  await p.locator('main').getByText('English', { exact: true }).click()
  await p.getByTestId('primary').first().click()
  await p.locator('main button[aria-pressed]:not(.rounded-full)').nth(0).click()
  await p.getByTestId('primary').first().click()
  await p.getByTestId('primary').first().click()
  for (const id of ['yes', 'stock', 'no', 'yes', 'no']) {
    await tid(`option-${id}`).click()
    await p.getByTestId('primary').first().click()
    await p.getByTestId('primary').first().click()
  }
  await tid('start-lesson').click()
  for (let i = 0; i < 3; i++) await p.getByTestId('primary').first().click()
  await tid('option-left').click(); await p.getByTestId('primary').first().click(); await p.getByTestId('primary').first().click()
  await tid('option-profit').click(); await p.getByTestId('primary').first().click(); await p.getByTestId('primary').first().click()
  await tid('option-down').click(); await p.getByTestId('primary').first().click(); await p.getByTestId('primary').first().click()
  await p.getByTestId('primary').first().click() // I'll do this
  ok((await tid('completion').getAttribute('data-result')) === 'understood', 'DL-01 understood')
  await p.getByTestId('primary').first().click() // Home
  await p.waitForSelector('[data-testid=home-challenge]')
  await shot('12-DL01-home-after-lesson')
  await p.setViewportSize({ width: 1280, height: 900 })
  await p.goto(BASE + '#/coach/learner/DL-01')
  await p.waitForSelector('[data-testid=coach-lessons]')
  ok((await tid('lesson-m1').getAttribute('data-status')) === 'completed', 'coach sees DL-01 lesson completed')
  ok((await tid('concept-m1').getAttribute('data-level')) === 'demonstrated', 'coach sees demonstrated')
  ok((await tid('challenge-next').getAttribute('data-agreed')) === 'true', 'coach sees DL-01 challenge (agreed this week)')
  ok((await tid('coach-assessment').innerText()).includes('Misconception'), 'coach sees assessment')
  note(`DL-01 after full flow → coach: next lesson = ${await tid('coach-recommended').getAttribute('data-lesson')} (${await tid('coach-recommended').getAttribute('data-source')})`)
  await shot('13-DL01-coach')
  // Mobile coach
  await p.setViewportSize({ width: 375, height: 812 })
  await p.reload()
  await p.waitForSelector('[data-testid=learner-detail]')
  await overflow('coach mobile')
  await shot('14-coach-mobile')
  await b.close()
  console.log(problems.length ? 'PROBLEMS:\n' + problems.join('\n') : 'ALL PROGRESS/COACH BROWSER CHECKS PASSED')
})()
