const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 375, height: 812 } })
  const p = await ctx.newPage()
  const errs = []
  p.on('pageerror', (e) => errs.push(e.message))
  await p.goto('http://localhost:4176/#/onboarding/language')
  await p.locator('main').getByText('తెలుగు', { exact: true }).click()
  await p.getByTestId('primary').first().click()
  await p.locator('main button[aria-pressed]:not(.rounded-full)').nth(1).click()
  await p.getByTestId('primary').first().click()
  await p.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith('hisaab.lesson')).forEach((k) => localStorage.removeItem(k)))
  await p.goto('http://localhost:4176/#/lessons/m1')
  await p.waitForTimeout(2500)
  console.log('no key → read-aloud:', await p.getByTestId('tts-fallback').first().getAttribute('data-reason').catch(() => 'controls shown'))
  for (let i = 0; i < 3; i++) await p.getByTestId('primary').first().click()
  await p.waitForTimeout(500)
  console.log('no key → mic button present (browser STT path):', await p.getByTestId('stt-mic').count())
  await ctx.setOffline(true)
  await p.waitForTimeout(500)
  console.log('offline banner:', await p.getByTestId('offline-banner').innerText())
  console.log('offline voice-answer notice shown:', await p.getByTestId('stt-offline').count())
  await p.screenshot({ path: '' + (process.env.SHOTS_DIR || require('os').tmpdir()) + '/shots/X-offline.png' })
  console.log('errors', errs)
  await b.close()
})()
