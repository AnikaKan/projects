// Coach View (coaching assistant) in a real Chromium against the production build.
//   npm run build && npx vite preview --port 4176 ; npm run server ; node tests/e2e/coach-e2e.cjs
// Fictional demo learners only. Speech output is the browser's own engine (may have no voice in CI: the
// app then shows its "no voice" notice). No API keys: the optional AI wording must fall back.
const { chromium } = require('playwright')
const SP = process.env.SHOTS_DIR || require('os').tmpdir()
const BASE = process.env.BASE || 'http://localhost:4176/'
const problems = []
const log = []
const ok = (c, m) => { log.push(`${c ? 'PASS' : 'FAIL'}  ${m}`); if (!c) problems.push(m) }
require('fs').mkdirSync(`${SP}/shots`, { recursive: true })
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 360, height: 780 } })
  const p = await ctx.newPage()
  p.on('pageerror', (e) => problems.push('pageerror ' + e.message))
  p.on('console', (m) => m.type() === 'error' && !/Failed to load resource|503/.test(m.text()) && problems.push('console ' + m.text()))
  const tid = (t) => p.getByTestId(t)
  const shot = (n) => p.screenshot({ path: `${SP}/shots/C-${n}.png` })
  const overflow = async (label) => ok(!(await p.evaluate(() => [...document.querySelectorAll('*')].some((e) => e.scrollWidth > e.clientWidth + 1 && getComputedStyle(e).overflowX === 'visible' && e.getBoundingClientRect().right > innerWidth + 1) || document.documentElement.scrollWidth > innerWidth + 1)), `${label}: no horizontal overflow at 360 px`)

  // ── 1. Coach home
  await p.goto(BASE + '#/coach')
  await p.waitForSelector('[data-testid=coach-list]')
  const count = async (t) => Number(await tid(t).getAttribute('data-count'))
  ok((await count('stat-all')) === 6 && (await count('stat-attention')) === 5 && (await count('stat-challenges')) === 3 && (await count('stat-ready')) === 2, 'Home: 6 active · 5 need attention · 3 activities to follow up · 2 ready for next lesson')
  const statuses = await p.getByTestId(/^roster-DL-\d+$/).evaluateAll((els) => els.map((e) => e.dataset.status))
  ok(statuses.at(-1) === 'doingWell' && statuses[0] === 'followUp', `Home: most urgent first (${statuses.join(',')})`)
  await overflow('coach home')
  await shot('01-home-en')

  // ── 2. Profile + "Why this lesson?" (Saraswathi)
  await tid('roster-DL-02').click()
  await p.waitForSelector('[data-testid=coach-recommended]')
  ok((await tid('rec-action-text').innerText()).includes('selling ₹500 of vegetables does not mean she earned ₹500 in profit'), 'Profile: personalised coaching action for Saraswathi')
  await tid('why-toggle').click()
  const ev = await tid('why-evidence').locator('li').allInnerTexts()
  ok(ev.length >= 1 && ev.length <= 3 && /answered “Yes”/.test(ev[0]), `Why: ≤ 3 evidence points from her saved diagnostic answer (${ev.length})`)
  await tid('rec-simpler').click()
  await p.waitForSelector('[data-testid=rec-ai-off]')
  ok(true, 'AI wording without a key: approved wording stays, with a clear notice')
  await overflow('profile')
  await shot('02-profile-why')

  // ── 3. Guided session for Meena (DL-05, English): all five steps
  await p.goto(BASE + '#/coach/learner/DL-05/session')
  await p.waitForSelector('[data-testid=coach-session]')
  ok((await tid('coach-session').getAttribute('data-step')) === 'checkin', 'Session starts at Check in')
  await tid('session-ci-done').click()
  await tid('session-ci-save').click()
  await tid('session-verify-partly').click()
  await shot('03-session-checkin')
  await tid('session-next').click()
  await p.waitForSelector('[data-testid=step-review]')
  ok((await tid('step-review').getAttribute('data-mis')) === 'misconception_ignores_hidden_costs', 'Review: the misconception from her practice answer')
  await tid('session-next').click()
  ok(await tid('step-teach').isVisible(), 'Teach step shown')
  await tid('session-next').click()
  await p.waitForSelector('[data-testid=step-practice]')
  const opts = p.locator('[data-testid^=practice-opt-]')
  const outcomes = await opts.evaluateAll((els) => els.map((e) => e.dataset.outcome))
  await opts.nth(outcomes.indexOf('correct')).click()
  ok((await tid('practice-feedback').getAttribute('data-outcome')) === 'correct', 'Practice: answer recorded and feedback shown')
  await overflow('session practice')
  await shot('04-session-practice')
  await tid('session-next').click()
  await p.waitForSelector('[data-testid=step-action]')
  const agree = p.locator('[data-testid^=action-agree-]').first()
  await agree.click()
  await tid('note-cat-needsPractice').click()
  await tid('note-save').click()
  await shot('05-session-action')
  await tid('session-complete').click()
  await p.waitForSelector('[data-testid=session-done]')
  ok((await tid('session-recorded').innerText()).match(/Activity checked[\s\S]*Practice: 1 of 1 right[\s\S]*New activity agreed[\s\S]*Note saved/), 'Session summary lists what was recorded')
  await tid('session-to-profile').click()
  await p.waitForSelector('[data-testid=coach-log]')
  ok((await tid('coach-log').innerText()).includes('coaching session completed'), 'Profile history shows the completed session')
  ok((await tid('verify-box').getAttribute('data-verified')) === 'partly', 'Weekly activity: coach check "partly" saved')
  await p.reload()
  await p.waitForSelector('[data-testid=coach-log]')
  ok((await tid('coach-log').innerText()).includes('coaching session completed'), 'Session result persists after reload')

  // ── 4. Pause / resume across a reload (Saraswathi)
  await p.goto(BASE + '#/coach/learner/DL-02/session')
  await p.waitForSelector('[data-testid=coach-session]')
  await tid('session-go-practice').click()
  await p.reload() // app closed mid-session
  await p.goto(BASE + '#/coach/learner/DL-02')
  await p.waitForSelector('[data-testid=start-session]')
  ok((await tid('start-session').getAttribute('data-resume')) === 'true', 'Unfinished session offered for resume after reload')
  await tid('start-session').click()
  await p.waitForSelector('[data-testid=coach-session]')
  ok((await tid('coach-session').getAttribute('data-step')) === 'practice', 'Resumed at the step where it stopped')
  ok((await tid('practice-text').getAttribute('lang')) === 'te', 'Learner-facing practice in her language (Telugu)')
  await tid('session-pause').click()

  // ── 5. Hindi and Telugu Coach View, preview languages
  for (const [code, word] of [['hi', 'आज किस पर काम करें?'], ['te', 'ఈ రోజు దేనిపై పని చేద్దాం?']]) {
    await tid(`coach-lang-${code}`).click()
    await p.waitForSelector('[data-testid=coach-recommended]')
    ok((await tid('coach-recommended').innerText()).includes(word), `Coach View in ${code}`)
    await overflow(`profile ${code}`)
    await shot(`06-profile-${code}`)
  }
  await tid('coach-lang-more').click()
  await tid('coach-lang-soon-bn').click()
  ok((await tid('coach-lang-soon-note').innerText()).includes('বাংলা'), 'Bengali shown as coming soon')
  ok((await tid('coach-lang-te').getAttribute('aria-pressed')) === 'true', 'Preview language does not switch the Coach View language')
  await tid('coach-lang-en').click()

  // ── 6. Offline: the coaching workflow keeps working on the device
  await p.goto(BASE + '#/coach')
  await p.evaluate(async () => { await navigator.serviceWorker.ready })
  await p.reload()
  await ctx.setOffline(true)
  await p.goto(BASE + '#/coach/learner/DL-03')
  await p.reload()
  await p.waitForSelector('[data-testid=learner-detail]')
  ok((await tid('coach-sync').getAttribute('data-online')) === 'false', 'Offline: Coach View opens from the cache and says it is offline')
  ok((await tid('prototype-banner').innerText()).includes('No server sync'), 'Sync limitation stated plainly')
  await tid('add-note').click()
  await tid('note-cat-languageDifficulty').click()
  await tid('note-save').click()
  await tid('start-session').click()
  await tid('session-ci-notYet').click()
  await tid('session-diff-noTime').click()
  await tid('session-ci-save').click()
  await tid('session-pause').click()
  await p.reload()
  await p.waitForSelector('[data-testid=notes-list]')
  ok((await tid('notes-list').innerText()).includes('Difficulty with language'), 'Offline: note saved on the device and still there after reload')
  ok((await tid('challenge-DL-03-ch1').getAttribute('data-display')) === 'notCompleted', 'Offline: check-in saved on the device')
  await shot('07-offline')
  await ctx.setOffline(false)

  // ── 7. Reset needs confirmation
  await tid('coach-reset').click()
  ok(await p.getByRole('dialog').isVisible(), 'Reset asks for confirmation before deleting')
  await p.getByRole('dialog').getByRole('button').nth(1).click() // cancel
  ok((await tid('challenge-DL-03-ch1').getAttribute('data-display')) === 'notCompleted', 'Cancel keeps the data')

  // ── 8. Learner side unaffected: the learner app never links to Coach View
  await p.goto(BASE + '#/home')
  await p.waitForSelector('main')
  ok((await p.locator('a[href="#/coach"]').count()) === 0, 'No Coach View link in the learner app')

  await b.close()
  console.log(log.join('\n'))
  console.log(problems.length ? `PROBLEMS:\n${problems.join('\n')}` : `COACH VIEW: ALL ${log.length} CHECKS PASSED`)
})()
