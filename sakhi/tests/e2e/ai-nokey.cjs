const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 375, height: 812 } })
  const errs = []; p.on('pageerror', (e) => errs.push(e.message))
  let posts = 0; p.on('request', (r) => r.url().includes('/api/explain') && posts++)
  await p.goto('http://localhost:4176/#/onboarding/language')
  await p.locator('main').getByText('తెలుగు', { exact: true }).click(); await p.getByTestId('primary').first().click()
  await p.locator('main button[aria-pressed]:not(.rounded-full)').nth(1).click(); await p.getByTestId('primary').first().click()
  await p.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith('hisaab.lesson')).forEach((k) => localStorage.removeItem(k)))
  await p.goto('http://localhost:4176/#/lessons/m1'); await p.waitForTimeout(300)
  await p.getByTestId('primary').first().click()
  const before = await p.getByTestId('explanation').innerText()
  await p.getByTestId('another-way').click(); await p.waitForTimeout(800)
  console.log('no key, intro: approved variant changed =', before !== (await p.getByTestId('explanation').innerText()), '| hidden card reason =', await p.getByTestId('ai-hidden').getAttribute('data-reason'))
  for (let i = 0; i < 2; i++) await p.getByTestId('primary').first().click()
  await p.getByTestId('another-way').click(); await p.waitForTimeout(800)
  console.log('no key, response: card =', await p.getByTestId('ai-card').getAttribute('data-source'), await p.getByTestId('ai-card').getAttribute('data-reason'), '|', await p.getByTestId('ai-text').innerText())
  await p.getByTestId('another-way').click(); await p.waitForTimeout(500)
  console.log('requests to /api/explain:', posts, '(second tap answered locally)'); console.log('errors', errs)
  await p.screenshot({ path: '' + (process.env.SHOTS_DIR || require('os').tmpdir()) + '/shots/AI-te-nokey.png', fullPage: true })
  await b.close()
})()
